"""Summarize results/ into results/summary.md and two plots. Reads files; makes no API calls."""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from evaljev import metrics as M
from evaljev.data import SST5_LABELS, tasks
from evaljev.run import RESULTS, read

PALETTE = ["#2f6fdf", "#d9822b", "#7a7a7a", "#2a9d8f", "#9b5de5", "#e63946", "#264653", "#f4a261"]


def models() -> list[str]:
    """Every model slug with a main results file in every task; Jev first."""
    found = None
    for t in tasks():
        here = {p.stem for p in (RESULTS / t).glob("*.jsonl") if "~" not in p.stem}
        found = here if found is None else found & here
    found = sorted(found or [])
    return ["jev"] + [m for m in found if m != "jev"] if "jev" in found else found


def label(m: str) -> str:
    if m == "jev":
        return "Jev"
    name, _, effort = m.partition("+")
    return name.replace("__", "/") + (f" (reasoning: {effort})" if effort else "")


MODELS: list[str] = []
LABEL: dict[str, str] = {}
COLOR: dict[str, str] = {}


def latest(path: Path) -> list[dict]:
    """One record per id: the last successful line wins (resume can leave earlier error lines)."""
    by_id = {}
    for r in read(path):
        if not r.get("error"):
            by_id[r["id"]] = r
    return list(by_id.values())


def summarize(task: str, model: str) -> dict:
    rs = latest(RESULTS / task / f"{model}.jsonl")
    gold, pred = [r["gold"] for r in rs], [r["pred"] for r in rs]
    conf = [r["conf"] for r in rs]
    ok = [g == p for g, p in zip(gold, pred)]
    lat = [r["latency_s"] for r in rs]
    s = {
        "n": len(rs),
        "acc": M.accuracy(ok),
        "ci": M.wilson(sum(ok), len(ok)),
        "f1": M.macro_f1(gold, pred),
        "ece": M.ece(conf, ok),
        "brier": M.brier(conf, ok),
        "auroc": M.auroc(conf, ok),
        "conf": float(np.mean(conf)),
        "p50": M.percentile(lat, 50),
        "p95": M.percentile(lat, 95),
        "usd_1k": 1000 * float(np.mean([r["cost_usd"] for r in rs])),
        "in_tok": float(np.mean([r["in_tok"] for r in rs])),
        "selective": M.selective(conf, ok),
        "rel": M.reliability(conf, ok),
        "_conf": conf,
        "_ok": ok,
    }
    if task == "sentiment5":
        s["mae"] = M.ordinal_mae(gold, pred, SST5_LABELS)
    return s


def determinism(task: str) -> tuple[float, float]:
    a = {r["id"]: r for r in latest(RESULTS / task / "jev.jsonl")}
    b = {r["id"]: r for r in latest(RESULTS / task / "jev~rerun.jsonl")}
    ids = a.keys() & b.keys()
    same = M.agreement({i: a[i]["pred"] for i in ids}, {i: b[i]["pred"] for i in ids})
    drift = float(np.mean([max(abs(a[i]["probs"][k] - b[i]["probs"][k]) for k in a[i]["probs"]) for i in ids]))
    return same, drift


def plots(S: dict) -> None:
    T = list(S)
    fig, axes = plt.subplots(1, len(T), figsize=(4.4 * len(T), 4.2), squeeze=False)
    axes = axes[0]
    for ax, task in zip(axes, T):
        ax.plot([0, 1], [0, 1], ls=":", c="#999", lw=1)
        for m in MODELS:
            rel = S[task][m]["rel"]
            ax.plot([x for x, _, _ in rel], [y for _, y, _ in rel], "o-", c=COLOR[m], label=LABEL[m],
                    ms=3, lw=1.5)
        ax.set(title=task, xlabel="stated confidence", xlim=(0, 1.02), ylim=(0, 1.02))
    axes[0].set_ylabel("actual accuracy")
    axes[0].legend(fontsize=8, loc="upper left")
    fig.suptitle("Reliability: points on the diagonal mean confidence matches accuracy", fontsize=11)
    fig.tight_layout()
    fig.savefig(RESULTS / "reliability.png", dpi=130)

    fig, axes = plt.subplots(1, len(T), figsize=(4.4 * len(T), 4.2), squeeze=False)
    axes = axes[0]
    for ax, task in zip(axes, T):
        for m in MODELS:
            conf, ok = np.array(S[task][m]["_conf"]), np.array(S[task][m]["_ok"])
            order = np.argsort(-conf, kind="stable")
            cov = np.arange(1, len(conf) + 1) / len(conf)
            ax.plot(cov, np.cumsum(ok[order]) / np.arange(1, len(conf) + 1), c=COLOR[m], label=LABEL[m], lw=1.5)
        ax.set(title=task, xlabel="coverage (share of items acted on, most confident first)", ylim=(0.4, 1.01))
    axes[0].set_ylabel("accuracy on acted-on items")
    axes[0].legend(fontsize=8, loc="lower left")
    fig.suptitle("Act-or-escalate: accuracy if the model only acts on its most confident items", fontsize=11)
    fig.tight_layout()
    fig.savefig(RESULTS / "coverage.png", dpi=130)


def main() -> None:
    MODELS[:] = models()
    LABEL.update({m: label(m) for m in MODELS})
    COLOR.update({m: PALETTE[i % len(PALETTE)] for i, m in enumerate(MODELS)})
    TASKS = {t: json.loads((RESULTS.parent / "data" / f"{t}.task.json").read_text()) for t in tasks()}
    for t in TASKS:
        TASKS[t]["hf"] = t
    S = {t: {m: summarize(t, m) for m in MODELS} for t in TASKS}
    L = ["# Results summary", "", "Generated by `uv run python -m evaljev.report` from `results/*/*.jsonl`.", ""]
    for task, spec in TASKS.items():
        n = S[task]["jev"]["n"]
        L += [f"## {task} (Jev `{spec['kind']}`, n={n})", "",
              "| model | accuracy [95% CI] | macro-F1 | ECE ↓ | Brier ↓ | AUROC ↑ | mean conf | p50 / p95 latency | $ per 1k calls |",
              "|---|---|---|---|---|---|---|---|---|"]
        for m in MODELS:
            s = S[task][m]
            L.append(f"| {LABEL[m]} | {s['acc']:.3f} [{s['ci'][0]:.3f}, {s['ci'][1]:.3f}] | {s['f1']:.3f} | "
                     f"{s['ece']:.3f} | {s['brier']:.3f} | {s['auroc']:.3f} | {s['conf']:.3f} | "
                     f"{s['p50']:.2f}s / {s['p95']:.2f}s | ${s['usd_1k']:.4f} |")
        if task == "sentiment5":
            L += ["", "Ordinal MAE (levels off, lower is better): " +
                  ", ".join(f"{LABEL[m]} {S[task][m]['mae']:.3f}" for m in MODELS)]
        L += ["", "Act only when confidence ≥ threshold (coverage / accuracy on covered):", "",
              "| model | " + " | ".join(f"≥{t}" for t in M.THRESHOLDS) + " |",
              "|---|" + "---|" * len(M.THRESHOLDS)]
        for m in MODELS:
            L.append(f"| {LABEL[m]} | " + " | ".join(
                f"{c:.0%} / {a:.3f}" if c else "0% / –" for _, c, a in S[task][m]["selective"]) + " |")
        if "jev" in S[task]:
            j = S[task]["jev"]
            for m in MODELS:
                if m == "jev":
                    continue
                t = S[task][m]
                L += ["", f"Jev vs {LABEL[m]}: {t['p50'] / j['p50']:.1f}x faster at p50, {t['usd_1k'] / j['usd_1k']:.0f}x cheaper "
                          f"per call, mean input tokens {j['in_tok']:.0f} vs {t['in_tok']:.0f}."]
            if (RESULTS / task / "jev~rerun.jsonl").exists():
                same, drift = determinism(task)
                L += [f"Jev rerun on identical inputs: same label {same:.1%}, mean max |Δprob| {drift:.3f}."]
            L += [""]
    total = {m: sum(S[t][m]["usd_1k"] * S[t][m]["n"] / 1000 for t in TASKS) for m in MODELS}
    L += ["## Spend (main result files)", ""]
    L += [f"- {LABEL[m]}: ${total[m]:.4f}" for m in MODELS]
    L += ["", "![reliability](reliability.png)", "", "![coverage](coverage.png)", ""]
    (RESULTS / "summary.md").write_text("\n".join(L))
    plots(S)
    print("\n".join(L))


if __name__ == "__main__":
    main()
